/**
 * user-profile.ts — the DEVICE half of the user's own name (SCRUM-214(A) option B).
 *
 * ⚠️ The RULES live in `user-name.ts`, pure, so `check:lib` can assert them under plain Node — see that file's
 * header for why the split is not optional (the first attempt was one file and the gate crashed on a native
 * polyfill import).
 *
 * ⚠️ **NO RPC, and that is the design, not a shortcut.** `profiles` already carries `profiles_select_own` and
 * `profiles_update_own`, both `user_id = auth.uid()` — so PostgREST can read and write exactly the caller's row
 * and nothing else. ⚠️ A `SECURITY DEFINER` function to set a scalar on one's own row would add privilege where
 * none is needed; RLS is the authority here. ⚠️ The `.eq('user_id', uid)` is belt-and-braces: RLS already scopes
 * the update, and naming the row keeps the statement honest if a policy is ever widened by mistake.
 */

import type { ApiResult } from './clan-api.ts';
import { supabase } from './supabase.ts';
import { chosenNameProblem, normaliseChosenName } from './user-name.ts';

/** What the screen needs about the caller. */
export interface MyName {
  /** ⚠️ `null` is a real state — the user has not chosen one yet, and the screen says so. */
  readonly chosenName: string | null;
  /** ⚠️ The autogenerated league pseudonym, READ ONLY here. It is never written by the client (doc 13 §4). */
  readonly pseudonym: string | null;
  /** ⚠️ The signed-in address — a USER profile should answer *"which account am I?"*. */
  readonly email: string | null;
}

export async function readMyName(): Promise<ApiResult<MyName>> {
  const { data, error } = await supabase()
    .from('profiles')
    .select('chosen_name, display_label')
    .maybeSingle();
  if (error) return { ok: false, reason: reasonOf(error) };

  const row = (data ?? {}) as Record<string, unknown>;
  const text = (v: unknown): string | null =>
    typeof v === 'string' && v.trim().length > 0 ? v : null;

  /**
   * ⚠️ The address comes from AUTH, not from `profiles` — the profile row is not where an email lives, and an
   * anonymous session has none at all. ⚠️ A failed read here is not fatal to the screen: the name is the
   * point, the address is context, so it degrades to `null` rather than failing the whole read.
   */
  let email: string | null = null;
  try {
    const { data: userData } = await supabase().auth.getUser();
    const raw = userData?.user?.email;
    email = typeof raw === 'string' && raw.length > 0 ? raw : null;
  } catch {
    email = null;
  }

  return {
    ok: true,
    data: { chosenName: text(row.chosen_name), pseudonym: text(row.display_label), email },
  };
}

/**
 * Set the caller's own name. ⚠️ Validated here AND by the column's CHECK, because a round trip is not a
 * validation strategy.
 */
export async function setChosenName(raw: string): Promise<ApiResult<string>> {
  const name = normaliseChosenName(raw);
  const problem = chosenNameProblem(name);
  if (problem !== null) return { ok: false, reason: problem };

  const { data: userData, error: userError } = await supabase().auth.getUser();
  const uid = userData?.user?.id;
  if (userError || !uid) return { ok: false, reason: 'not_authenticated' };

  const { error } = await supabase().from('profiles').update({ chosen_name: name }).eq('user_id', uid);
  if (error) return { ok: false, reason: reasonOf(error) };
  return { ok: true, data: name };
}

/** The same shape `clan-api.ts` uses — a stable reason, never a thrown error. */
function reasonOf(error: unknown): string {
  if (typeof error === 'object' && error !== null) {
    const message = (error as { message?: unknown }).message;
    if (typeof message === 'string' && message.length > 0) return message;
  }
  return 'request_failed';
}
