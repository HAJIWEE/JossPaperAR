-- ══════════════════════════════════════════════════════════════════════════════
-- 20261108120000_profile_chosen_name — the USER's own name, with the pseudonym left alone
--
-- ── WHY (owner, 2026-11-08 · SCRUM-214(A) option B) ───────────────────────────
-- *"Profile should be a User Profile as we already have a Clan page where the Clan details are shown."*
-- ⚠️ The Profile screen had nothing user-scoped to show — its header carried the CLAN name and role, which
-- the Clan page already owns — because the only per-user string in the schema was `profiles.display_label`.
--
-- ⚠️⚠️ AND `display_label` CANNOT BE IT. It is auto-generated by `pseudonym_for(new.id)` on sign-in, and the
-- table comment says it is the league pseudonym — *"NEVER the ancestor name"* (doc 13 §4). Writing a name a
-- person chose into the pseudonym would put a real identity into a privacy device that exists to avoid one.
-- So the user's name gets its OWN column, and `display_label` keeps doing exactly what it does today.
--
-- ── ⚠️ WHAT THIS COLUMN IS NOT ───────────────────────────────────────────────
-- · NOT unique. ⚠️ **Duplicate account names are ALLOWED** (owner, 2026-11-08) — people share names, and the
--   identity is `user_id` / the email, never the label. A `unique` here would be a rule nobody asked for.
-- · NOT the clan name. A family name belongs to `clans.name` (doc 15 §2.1) and is set on the Clan page.
-- · NOT exposed to anyone else. ⚠️ Verified before adding it: no RPC selects `p.*` from `profiles` (the two
--   joins — `clan_management_api` and `league_roll_engine` — name their columns), and the RLS policies are
--   `user_id = auth.uid()` for select AND update, so only the owner can read or write it.
-- · NOT a new erasure problem. ⚠️ `delete_my_data` does `delete from public.profiles where user_id = v_uid`,
--   so the column is erased with the row — and the re-minted anonymous identity gets a fresh profile.
--
-- ⚠️ Nullable on purpose: every existing account has no name yet, and "no name" is a real state the Profile
-- screen renders as a call to action rather than an error.
-- ══════════════════════════════════════════════════════════════════════════════

alter table public.profiles
  add column chosen_name text
    check (
      chosen_name is null
      or (char_length(btrim(chosen_name)) between 1 and 24)
    );

comment on column public.profiles.chosen_name is
  'The name the USER chose for their own profile (SCRUM-214A option B). ⚠️ NOT the league pseudonym — that is display_label, which must stay auto-generated and must NEVER carry a real name (doc 13 §4). ⚠️ NOT the clan/family name — that is clans.name, shown on the Clan page. Duplicates are allowed: the identity is user_id, not this label. Erased with the profiles row by delete_my_data.';

-- ⚠️ `btrim` in the CHECK means a name of only spaces cannot reach 1 character — the client trims too, but the
-- database is the authority on what it stores (the same rule `clan.name` follows).
